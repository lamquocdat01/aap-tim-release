#!/usr/bin/env python3
r"""The E4 three-column in-situ FAR table, generated from generated_counts.json.

    python far_strata_table.py [--out DIR]

WHY THIS IS A SCRIPT AND NOT A TABLE IN A FILE

    E4 section 2.6 requires all THREE numbers -- pooled, native, substituted --
    to be reported for every checker on every branch of the flag, so that the
    branch the rule chose cannot be read off the table by which columns are
    present. A table typed once and edited later is how two of the three drift.
    Every cell here is read from `generated_counts.json`, which is itself
    counted from the run metadata; nothing in this file is a number.

    The flag resolved `false` on 2026-09-06, so the pooled column is the
    headline and the other two are the disclosure. Had it resolved `true` the
    same table would be printed with native as the headline: that is why the
    caption is chosen by the flag rather than written by hand.

Writes FAR_STRATA.md and far_strata.tex. Standard library only.
"""

from __future__ import annotations

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MEAS = os.path.dirname(HERE)
COUNTS = os.path.join(MEAS, "generated_counts.json")


def fmt(v, nd=2):
    return ("%%.%df" % nd) % float(v)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--out", default=MEAS)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)

    C = json.load(open(COUNTS, encoding="utf-8"))
    roster = [c.strip() for c in C["far_checker_roster"].split(",")]
    flag = C.get("flag_subst_stratum_separated")
    if flag == "[TBD]":
        sys.exit("refusing: the E4 flag is still [TBD]; no branch may be printed "
                 "(E4 2.4). Nothing was written.")

    pooled_n, pooled_h = C["far_pooled_n"], C["far_pooled_hours"]
    nat_n, nat_h = C["far_native_n"], C["far_native_hours"]
    sub_n, sub_h = C["far_subst_n"], C["far_subst_hours"]

    headline = "pooled" if flag == "false" else "native"
    caption = (
        "In-situ alert rate per checker, by clock stratum (pre-registration E4). "
        "The separation flag resolved \\texttt{%s}: %s. All three columns are "
        "reported on either branch, so the branch taken cannot be inferred from "
        "which numbers are shown. Intervals are two-sided 95\\%%; a zero count "
        "uses the Poisson upper limit, a non-zero count a segment-level block "
        "bootstrap (seed 20260905)."
        % (flag,
           ("the substituted stratum is not distinguishable from the native one "
            "for any checker, so the %d pooled segments (%s h) are the headline "
            "denominator" % (pooled_n, fmt(pooled_h, 4)))
           if flag == "false" else
           ("the substituted stratum is separated as a recorder artefact, so the "
            "%d native segments (%s h) are the headline denominator"
            % (nat_n, fmt(nat_h, 4)))))

    rows = []
    for ck in roster:
        k = ck.lower()
        rows.append({
            "checker": ck,
            "pa": C["far_%s_pooled_alerts" % k], "pr": C["far_%s_pooled_rate" % k],
            "na": C["far_%s_native_alerts" % k], "nr": C["far_%s_native_rate" % k],
            "sa": C["far_%s_subst_alerts" % k], "sr": C["far_%s_subst_rate" % k],
            "lo": C["far_%s_subst_ci_lo" % k], "hi": C["far_%s_subst_ci_hi" % k],
            "m": C["far_%s_subst_ci_method" % k],
        })

    md = ["# In-situ FAR by clock stratum (E4)", "",
          "Generated by `01_Measurement/scripts/far_strata_table.py` from",
          "`generated_counts.json` (%s). Not hand-edited." % C.get("_generated_at", "?"),
          "",
          "Flag `flag_subst_stratum_separated` = **%s** — headline stratum: **%s**."
          % (flag, headline), "",
          "| checker | pooled %d seg / %s h | native %d seg / %s h | substituted %d seg / %s h | substituted 95%% CI | CI method |"
          % (pooled_n, fmt(pooled_h, 4), nat_n, fmt(nat_h, 4), sub_n, fmt(sub_h, 4)),
          "|---|---:|---:|---:|---|---|"]
    for r in rows:
        md.append("| %s | %d (%s/h) | %d (%s/h) | %d (%s/h) | [%s, %s] | %s |"
                  % (r["checker"], r["pa"], fmt(r["pr"]), r["na"], fmt(r["nr"]),
                     r["sa"], fmt(r["sr"]), fmt(r["lo"]), fmt(r["hi"]), r["m"]))
    md += ["", "**Basis recorded by the rule:** " + C["far_flag_basis"], "",
           "A checker with zero alerts in both strata is a measurement, not a gap:",
           "the substituted stratum's %s h can only exclude a rate above"
           % fmt(sub_h, 4),
           "%s alert/h, so a low-rate checker cannot be separated even in principle."
           % fmt(C["far_subst_zero_count_upper_limit"], 4)]
    p = os.path.join(a.out, "FAR_STRATA.md")
    open(p, "w", encoding="utf-8").write("\n".join(md) + "\n")

    tex = [r"% GENERATED by 01_Measurement/scripts/far_strata_table.py -- DO NOT EDIT.",
           r"\begin{table}[t]", r"\centering",
           r"\caption{%s}" % caption, r"\label{tab:far-strata}",
           r"\begin{tabular}{lrrrl}", r"\hline",
           r"checker & pooled & native & substituted & substituted 95\% CI \\",
           r"        & \multicolumn{3}{c}{alerts (rate h$^{-1}$)} & \\ \hline"]
    for r in rows:
        tex.append(r"%s & %d (%s) & %d (%s) & %d (%s) & [%s, %s] \\"
                   % (r["checker"].replace("Checker", ""), r["pa"], fmt(r["pr"]),
                      r["na"], fmt(r["nr"]), r["sa"], fmt(r["sr"]),
                      fmt(r["lo"]), fmt(r["hi"])))
    tex += [r"\hline", r"\end{tabular}", r"\end{table}"]
    q = os.path.join(a.out, "far_strata.tex")
    open(q, "w", encoding="utf-8").write("\n".join(tex) + "\n")

    print("flag=%s, headline=%s, %d checkers" % (flag, headline, len(rows)))
    print("wrote %s" % p)
    print("wrote %s" % q)


if __name__ == "__main__":
    main()
